#!/usr/bin/env python3
"""평가셋 — LLM 이 제목만 보고 처음부터 쓴 한국어 초록 생성용 프롬프트.

왜 필요한가:
  MASH 의 ASR 은 $\\mathcal{D}_{pair}$ 가 아니라 **벤치마크의 진짜 기계 생성문**에 대해 잰다
  (`MASH.md:522`, "randomly sample 100 machine-generated instances per domain for testing").
  우리 학습쌍의 $x_{ai}$ 는 인간 초록을 다시 쓴 것이라 성격이 다르다 — 그걸로 ASR 을 재면
  "패러프레이즈를 되돌리는 능력"을 재는 셈이 되어 공격 성능을 과대평가한다.
  그래서 humanizer 가 실제로 상대할 입력, 즉 **사람이 ChatGPT 로 초록을 뽑았을 때 나오는 글**을
  따로 만든다.

설계:
  · 입력은 제목뿐이다. 원문 초록을 주면 재서술이 되어 목적이 어긋난다.
  · 분량은 대응하는 인간 초록의 길이에 맞춘다 — 길이 차이가 탐지 신호로 새는 것을 막는다.
  · 연구분야를 함께 준다. 제목만으로는 장르가 흔들려 초록이 아닌 글이 나오기 쉽다.
  · 학습쌍과 **원문이 겹치지 않아야 한다**. collect_kci.py --exclude 로 분리해 받은
    `mash/kci_human_ko_eval.jsonl` 을 쓴다.

이 300편은 두 가지로 동시에 쓰인다:
  ① AI 초록 300편 → humanizer 의 공격 대상 (ASR 측정)
  ② 인간 초록 300편 → 카피킬러 오탐률 추가 표본 (누적 n=450)

사용:
  python3 build_eval_prompts.py --in mash/kci_human_ko_eval.jsonl \
      --out mash/prompts_eval_ai.jsonl
"""
import argparse
import json
import re
from pathlib import Path

# ── 모드 A: 재서술 (MGT-Academic 관례) ────────────────────────
# "Advanced LLMs generate these counterparts via academic paraphrasing or
#  completion" (MASH.md:520). 학술 도메인의 표준 구성 방식이다.
# 문구는 P3b(학습쌍 생성용)와 **일부러 다르게** 썼다 — 프롬프트까지 같으면
# 학습 분포를 그대로 평가하게 된다.
PARA_SYSTEM = "당신은 한국어 학술 문헌을 다루는 연구 보조원입니다."
PARA_USER = (
    "다음 학술 초록을 학술적 문체를 유지한 채 다시 쓰세요. "
    "연구의 내용과 사실관계는 그대로 두고 표현만 바꾸면 됩니다.\n"
    "다시 쓴 초록만 출력하세요 — 설명이나 제목, 마크다운 서식은 쓰지 마세요.\n\n{text}"
)

# ── 모드 B: 제목만 (MGTBench 관례 · 현실적 오남용 시나리오) ──
# "Its AI samples are generated by seven LLMs using task-specific prompts"
# (MASH.md:519). 연구자가 LLM 에게 초록을 통째로 맡기는 상황에 대응한다.
TITLE_SYSTEM = "당신은 한국어 학술 논문을 쓰는 연구자입니다."
TITLE_USER = (
    "다음 제목으로 학술 논문의 국문 초록을 작성하세요.\n"
    "{field}"
    "- 분량: 약 {n}자\n"
    "연구 목적, 방법, 결과, 결론이 드러나도록 쓰되 한 편의 이어지는 산문으로 작성하세요.\n"
    "초록 본문만 출력하세요 — 제목을 다시 쓰지 말고, 설명이나 머리말도 붙이지 마세요. "
    "굵은 글씨·별표(*)·불릿(-, •)·번호 목록 같은 서식은 쓰지 마세요.\n\n"
    "제목: {title}"
)

# 모드 C(이어쓰기)는 넣지 않는다. 인간 초록 앞부분이 AI 표본 안에 원문 그대로
# 남아, 러셀 트랙에서 조건 B 를 폐기한 것과 같은 복사 유출이 생긴다.


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--in", dest="inp", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--domain", default="abstract_eval")
    ap.add_argument("--mode", choices=["paraphrase", "title"], default="paraphrase")
    ap.add_argument("--limit", type=int, default=0)
    a = ap.parse_args()

    rows = [json.loads(l) for l in open(a.inp, encoding="utf-8") if l.strip()]
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    n = 0
    with out.open("w", encoding="utf-8") as f:
        for r in rows:
            title = (r.get("original_title") or "").strip()
            if not title:
                continue
            chars = len(r["original_abstract"])
            # 분야명은 한글 이름일 때만 넣는다. API 수집분은 코드(B210000)뿐인데
            # 그대로 넣으면 프롬프트가 오히려 모델을 혼란스럽게 한다.
            fld = r.get("research_field") or ""
            field = f"- 분야: {fld}\n" if re.search(r"[가-힣]", fld) else ""
            if a.mode == "paraphrase":
                system, prompt = PARA_SYSTEM, PARA_USER.format(text=r["original_abstract"])
            else:
                system, prompt = TITLE_SYSTEM, TITLE_USER.format(field=field, n=chars, title=title)
            f.write(json.dumps({
                "doc_id": f"eval-{r['kci_article_id']}",
                "cond": "EVAL_" + a.mode[:4].upper(),
                "domain": a.domain,
                "target_char": chars,
                "n_char": chars,
                "system": system,
                "prompt": prompt,
            }, ensure_ascii=False) + "\n")
            n += 1
            if a.limit and n >= a.limit:
                break
    print(f"평가용 프롬프트 {n}건 → {out}")
    print("  본 생성이 끝난 뒤 실행:")
    print(f"    python3 scripts/generate.py --in {out} --out mash/gen_eval_ai.jsonl \\")
    print("        --url http://127.0.0.1:8081/v1/chat/completions \\")
    print("        --model qwen3-8b --no-think --temp 0.8 --seed 42 --resume")


if __name__ == "__main__":
    main()
